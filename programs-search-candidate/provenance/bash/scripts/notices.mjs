import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";

const root = resolve(import.meta.dirname, "..");
const pins = JSON.parse(await readFile(resolve(root, "sources.lock.json"), "utf8"));
let output = "# Third-party notices\n\nThis file is generated by `npm run notices:shell`.\n\n";

async function include(label, directory) {
  const names = (await readdir(directory).catch(() => []))
    .filter((name) => /^(license|copying|notice)(\.|-|$)/i.test(name))
    .sort();
  for (const name of names) {
    const text = await readFile(resolve(directory, name), "utf8").catch(() => undefined);
    if (text) {
      const normalized = text.replaceAll("\r\n", "\n").replace(/[ \t]+$/gm, "");
      output += `## ${label} / ${name}\n\n${normalized}\n\n`;
    }
  }
}

const metadata = JSON.parse(
  execFileSync(
    "cargo",
    ["metadata", "--locked", "--format-version", "1", "--manifest-path", "shell/Cargo.toml"],
    { cwd: root, encoding: "utf8", maxBuffer: 16 * 1024 * 1024 },
  ),
);
const sed = JSON.parse(
  await readFile(resolve(root, "third-party/uutils-sed/provenance.json"), "utf8"),
);
output += `## uutils sed source\n\n${sed.repository} at ${sed.revision}. Local WASI changes are recorded in third-party/uutils-sed/wasi.patch.\n\n`;
const included = new Set();
const fileOperations = JSON.parse(
  await readFile(resolve(root, "shell/utilities/file-operations.source.json"), "utf8"),
);
const upstream = metadata.packages.find(
  (pkg) => pkg.name === "uucore" && pkg.source?.endsWith(`#${fileOperations.revision}`),
);
if (!upstream) throw new Error("Pinned file utility source is missing from Cargo metadata");
const upstreamRoot = resolve(dirname(upstream.manifest_path), "../..");
assert.equal(
  createHash("sha256")
    .update(await readFile(resolve(upstreamRoot, fileOperations.license.path)))
    .digest("hex"),
  fileOperations.license.sha256,
  "Pinned uutils root license digest",
);
const envSource = JSON.parse(
  await readFile(resolve(root, "shell/utilities/env.source.json"), "utf8"),
);
assert.equal(envSource.repository, fileOperations.repository);
assert.equal(envSource.revision, fileOperations.revision);
assert.deepEqual(envSource.license, fileOperations.license);
assert.deepEqual(envSource.sharedPackage, fileOperations.sharedPackage);
for (const [name, pkg] of Object.entries(envSource.packages)) {
  const resolved = metadata.packages.find((entry) => entry.name === name && entry.source === null);
  assert.ok(resolved, `Patched env source is missing from Cargo metadata: ${name}`);
  assert.equal(resolved.version, pkg.version);
  assert.equal(dirname(resolved.manifest_path), resolve(root, envSource.localPackage));
}
const envDirectory = resolve(root, envSource.localPackage);
const envProvenance = JSON.parse(await readFile(resolve(envDirectory, "provenance.json"), "utf8"));
assert.equal(envProvenance.repository, envSource.repository);
assert.equal(envProvenance.revision, envSource.revision);
for (const [path, digest] of Object.entries(envProvenance.files)) {
  assert.equal(
    createHash("sha256")
      .update(await readFile(resolve(envDirectory, path)))
      .digest("hex"),
    digest,
    `Patched env source digest: ${path}`,
  );
}
output += `## uutils env source\n\n${envSource.repository} at ${envSource.revision}. Local WASI changes are recorded in ${envSource.localPackage}/wasi.patch.\n\n`;
await include(`uutils coreutils ${fileOperations.revision}`, upstreamRoot);
for (const pkg of metadata.packages.sort((a, b) => a.name.localeCompare(b.name))) {
  if (included.has(pkg.manifest_path) || pkg.name === "shell-parser") continue;
  included.add(pkg.manifest_path);
  await include(`${pkg.name} ${pkg.version}`, dirname(pkg.manifest_path));
}
// Python is an optional, separately built payload. When distributed, require and
// include the full build-collected notices (including licenses inside bundled wheels).
if ((await readdir(resolve(root, "dist"))).includes("python.wasm")) {
  const pythonNotices = await readFile(resolve(root, "dist/python.NOTICES.txt"), "utf8");
  output += `## CPython 3.15.2 and full standard-library payload\n\n${pythonNotices}\n\n`;
}
const parserLicense = await readFile(resolve(root, pins.shellParser.directory, "LICENSE"), "utf8");
output += `## Bashkit parser ${pins.shellParser.revision} / LICENSE\n\n${parserLicense}\n\n`;
await include(`Oils corpus ${pins.oils.revision}`, resolve(root, "docs/evidence/licenses"));
await include(`Brush corpus ${pins.brush.revision}`, resolve(root, "docs/evidence/licenses"));
const oilsLicense = await readFile(
  resolve(root, "docs/evidence/licenses/oils-LICENSE.txt"),
  "utf8",
);
const brushLicense = await readFile(resolve(root, "docs/evidence/licenses/brush-MIT.txt"), "utf8");
output += `## Pinned Oils corpus ${pins.oils.revision}\n\n${oilsLicense}\n\n`;
output += `## Pinned Brush corpus ${pins.brush.revision}\n\n${brushLicense}\n`;
await mkdir(resolve(root, "dist"), { recursive: true });
await writeFile(resolve(root, "dist/THIRD_PARTY_NOTICES.txt"), output);
