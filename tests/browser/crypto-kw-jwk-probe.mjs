import assert from "node:assert/strict";
import {webcrypto} from "node:crypto";
import {installHostCrypto} from "../src/crypto-host.js";
const provider=webcrypto.subtle;
const wrap=provider.wrapKey.bind(provider);
let rawCalls=0;
provider.wrapKey=(format,key,wrapping,a)=>{
 if(format==="jwk" && a.name==="AES-KW") return Promise.reject(new DOMException("JWK is not aligned","DataError"));
 rawCalls++;return wrap(format,key,wrapping,a);
};
const c={isKey:()=>false,makeKey:()=>Object.create({}),encode:b=>Buffer.from(b).toString("base64url")};
installHostCrypto(provider,globalThis.CryptoKey,c,{utf8Encode:text=>new TextEncoder().encode(text)});
const data=new Uint8Array(16).fill(7);
const key=await provider.importKey("raw",data,{name:"HMAC",hash:"SHA-256"},true,["sign"]);
const wrapping=await provider.generateKey({name:"AES-KW",length:128},false,["wrapKey","unwrapKey"]);
const encrypted=await provider.wrapKey("jwk",key,wrapping,{name:"AES-KW"});
const back=await provider.unwrapKey("jwk",encrypted,wrapping,{name:"AES-KW"},{name:"HMAC",hash:"SHA-256"},true,["sign"]);
assert.deepEqual(new Uint8Array(await provider.exportKey("raw",back)),data);
assert.equal(rawCalls,1);
assert.equal(provider,webcrypto.subtle);
console.log("native AES-KW wraps aligned JWK bytes with a wrap-only key");
