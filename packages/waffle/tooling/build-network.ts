import { createHash } from "node:crypto";
import { copyFile, mkdir, readFile, readdir, writeFile, mkdtemp, rm } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join } from "node:path";
import { NETWORK_TRANSLATOR, provisionNetworkTranslator } from "./network-translator.js";
import { networkGrowth, verifyNetworkGrowth } from "./network-growth.js";

export const NETWORK_ASSETS = [
  "network.wasm",
  "network.sha256",
  "network.buffer.js",
  "network.buffer.sha256",
  "network.input-hash",
  "network.growth.json",
];
const checksum = (bytes: Uint8Array | string) => createHash("sha256").update(bytes).digest("hex");

export async function networkInputHash(root: string): Promise<string> {
  const hash = createHash("sha256");
  const inputs = [
    "Cargo.toml",
    "Cargo.lock",
    "rust-toolchain.toml",
    "network/Cargo.toml",
    "tooling/build-network.ts",
    "tooling/network-translator.ts",
    "tooling/network-translator/package.json",
    "tooling/network-translator/bun.lock",
    "tooling/network-growth.ts",
  ];
  for (const entry of (await readdir(join(root, "network/src"))).sort())
    inputs.push(`network/src/${entry}`);
  for (const path of inputs) {
    hash.update(path);
    hash.update(await readFile(join(root, path)));
  }
  return hash.digest("hex");
}

/** Verify restored bytes without invoking Cargo, including in browser jobs. */
export async function verifyNetwork(root: string): Promise<void> {
  const directory = join(root, "browser/net");
  const hash = await networkInputHash(root);
  if ((await readFile(join(directory, "network.input-hash"), "utf8")) !== hash)
    throw new Error("Network artifact input hash does not match this source");
  for (const [artifact, stamp] of [
    ["network.wasm", "network.sha256"],
    ["network.buffer.js", "network.buffer.sha256"],
  ]) {
    if (!artifact || !stamp) throw new Error("Invalid network artifact pair");
    const bytes = await readFile(join(directory, artifact));
    if ((await readFile(join(directory, stamp), "utf8")) !== checksum(bytes))
      throw new Error(`Network artifact checksum does not match ${artifact}`);
  }
  const growth: unknown = JSON.parse(
    await readFile(join(directory, "network.growth.json"), "utf8"),
  );
  verifyNetworkGrowth(growth);
  if (
    typeof growth !== "object" ||
    growth === null ||
    !("inputHash" in growth) ||
    growth.inputHash !== hash ||
    !("wasmSha256" in growth) ||
    growth.wasmSha256 !== (await readFile(join(directory, "network.sha256"), "utf8"))
  )
    throw new Error("Network growth proof does not match producer inputs and artifact");
}

async function compileNetwork(root: string): Promise<string> {
  if (process.env.WAFFLE_NETWORK_PREBUILT === "1")
    throw new Error(
      "Network artifact missing, stale or corrupt; Cargo and translation are forbidden in this job",
    );
  const target = process.env.CARGO_TARGET_DIR ?? join(root, "target");
  const child = Bun.spawn(
    [
      "cargo",
      "build",
      "-p",
      "waffle-tcp",
      "--release",
      "--target",
      "wasm32-unknown-unknown",
      "--locked",
    ],
    {
      cwd: root,
      env: { ...process.env, CARGO_TARGET_DIR: target },
      stdout: "inherit",
      stderr: "inherit",
    },
  );
  if ((await child.exited) !== 0)
    throw new Error(
      "Network WASM build failed. Install the pinned Rust toolchain and wasm32-unknown-unknown target.",
    );
  return join(target, "wasm32-unknown-unknown/release/waffle_tcp.wasm");
}

/** prepare reuses only an intact exact-input artifact, never stale restored bytes. */
export async function buildNetwork(root: string, compile = compileNetwork): Promise<void> {
  try {
    await verifyNetwork(root);
    return;
  } catch {
    // Local source installs rebuild; CI consumers reject here through compileNetwork.
  }
  const hash = await networkInputHash(root);
  const output = await compile(root);
  if (!existsSync(output)) throw new Error(`Network compiler did not produce ${output}`);
  const bytes = await readFile(output);
  const wasmSha256 = checksum(bytes);
  const growth = await networkGrowth(new Uint8Array(bytes));
  console.log(
    `Network allocator: ${growth.growthPages.length} slabs, max ${Math.max(...growth.growthPages)} pages, peak ${growth.peakPages} pages`,
  );
  const directory = join(root, "browser/net");
  const translated = await translateNetwork(output);
  await mkdir(directory, { recursive: true });
  await copyFile(output, join(directory, "network.wasm"));
  const generated = `// Generated by Binaryen 132.0.0 from network.wasm SHA-256 ${wasmSha256}.\n// Contains runtime support from Binaryen, Apache-2.0; see LICENSES/Apache-2.0.txt.\n// Copyright 2015 WebAssembly Community Group participants.\nexport ${translated}`;
  await writeFile(join(directory, "network.buffer.js"), generated);
  await writeFile(join(directory, "network.sha256"), wasmSha256);
  await writeFile(join(directory, "network.buffer.sha256"), checksum(generated));
  await writeFile(
    join(directory, "network.growth.json"),
    JSON.stringify({ inputHash: hash, wasmSha256, ...growth }),
  );
  // Publish the shared input stamp last: a partial build is never accepted.
  await writeFile(join(directory, "network.input-hash"), hash);
}
async function translateNetwork(wasm: string): Promise<string> {
  const executable = await provisionNetworkTranslator();
  const temporary = await mkdtemp(
    join(process.env.TMPDIR ?? (await import("node:os")).tmpdir(), "waffle-network-translate-"),
  );
  try {
    const raw = join(temporary, "network.js");
    const child = Bun.spawn(
      [process.execPath, executable].concat(NETWORK_TRANSLATOR.flags, [wasm, "-o", raw]),
      { stdout: "inherit", stderr: "inherit" },
    );
    if ((await child.exited) !== 0) throw new Error("Pinned network translation failed");
    const source = await readFile(raw, "utf8");
    if (!source.startsWith("function instantiate(info) {"))
      throw new Error("Unexpected network translator factory");
    return source;
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
}
if (import.meta.main) {
  const root = join(import.meta.dir, "..");
  if (process.argv.includes("--verify")) await verifyNetwork(root);
  else await buildNetwork(root);
}
